    package_root, lock = _load_verified_lock()
    commitment = lock.get("scorer")
    if (
        not isinstance(commitment, dict)
        or set(commitment) != {"path", "sha256", "bytes", "contract"}
        or commitment.get("path") != "scorer.py"
        or commitment.get("sha256") != EXPECTED_SCORER_SHA256
        or commitment.get("contract") != SCORER_CONTRACT
    ):
        raise RuntimeError("Lightwork scorer commitment is invalid")
    scorer_path = package_root / "scorer.py"
    scorer_blob = scorer_path.read_bytes()
    if (
        commitment.get("bytes") != len(scorer_blob)
        or hashlib.sha256(scorer_blob).hexdigest() != EXPECTED_SCORER_SHA256
    ):
        raise RuntimeError("Lightwork scorer integrity verification failed")
    module = types.ModuleType(f"{__package__}._verified_scorer")
