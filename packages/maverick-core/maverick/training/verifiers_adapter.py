    if (
        not isinstance(lock, dict)
        or lock.get("schema") != RUNTIME_LOCK_SCHEMA
        or lock.get("upstream", {}).get("version") != EXPECTED_VERIFIERS_VERSION
        or lock.get("upstream", {}).get("commit") != EXPECTED_VERIFIERS_COMMIT
    ):
        raise RuntimeError("Lightwork runtime lock is not compatible with this taskset")
    return package_root, lock


