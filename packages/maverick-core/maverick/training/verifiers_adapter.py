    if not isinstance(task_commitment, dict):
        raise RuntimeError("Lightwork runtime lock has no task commitment")
    tasks_blob = (package_root / "tasks.jsonl").read_bytes()
    if (
        task_commitment.get("bytes") != len(tasks_blob)
        or task_commitment.get("sha256")
        != hashlib.sha256(tasks_blob).hexdigest()
    ):
        raise RuntimeError("Lightwork task data integrity verification failed")

    lines = tasks_blob.splitlines()
