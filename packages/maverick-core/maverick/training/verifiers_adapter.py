def _load_verified_lock() -> tuple[Path, dict[str, Any]]:
    package_root = Path(__file__).parent
    lock_blob = (package_root / "bundle.lock.json").read_bytes()
    if hashlib.sha256(lock_blob).hexdigest() != EXPECTED_RUNTIME_LOCK_SHA256:
        raise RuntimeError("Lightwork runtime lock integrity verification failed")
